// Generates src/entities.ts from the WHATWG entities.json.
// Run: node scripts/gen-entities.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const data = JSON.parse(readFileSync(join(root, 'data/entities.json'), 'utf8'));

// Two maps:
//  - named: all entries whose key ends with ';' (the canonical list)
//  - legacy: entries without trailing ';' (HTML legacy ambiguous references)
const named = {};
const legacy = {};
for (const [key, value] of Object.entries(data)) {
  if (key.endsWith(';')) named[key] = value.characters;
  else legacy[key] = value.characters;
}

// Sorted key lists enable spec-compliant longest-prefix lookup via binary search.
const namedKeys = Object.keys(named).sort();
const legacyKeys = Object.keys(legacy).sort();

const out = `// AUTO-GENERATED by scripts/gen-entities.mjs — do not edit.
// Source: https://html.spec.whatwg.org/entities.json

/** Canonical named character references (all end with ';'). */
export const NAMED_ENTITIES: Readonly<Record<string, string>> = ${JSON.stringify(named)};

/** Legacy (no-semicolon) references, usable only in special parsing contexts. */
export const LEGACY_ENTITIES: Readonly<Record<string, string>> = ${JSON.stringify(legacy)};

/** Sorted keys for longest-prefix binary search. */
export const NAMED_ENTITY_KEYS: readonly string[] = Object.freeze(${JSON.stringify(namedKeys)});
export const LEGACY_ENTITY_KEYS: readonly string[] = Object.freeze(${JSON.stringify(legacyKeys)});
`;

writeFileSync(join(root, 'src/entities.ts'), out);
console.log(
  `entities.ts: ${namedKeys.length} canonical + ${legacyKeys.length} legacy references`
);
